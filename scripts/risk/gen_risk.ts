/** Escape a markdown table cell: pipes would split it, newlines would end it. */
const cell = (s: string | undefined): string =>
  (s ?? "—").replace(/\|/g, "\\|").replace(/\n+/g, " ");

const thresholdText = (f: ContractFlagDef | TenderFlagDef): string => {
  const t = f.threshold;
  if (!t) return "—";
  switch (t.kind) {
    case "gteRatio":
      return `≥ ${(t.value * 100).toFixed(0)}%`;
    case "ltDays":
      return `< ${t.value} days`;
    case "lteDays":
      return `≤ ${t.value} days`;
    case "ltMonths":
      return `< ${t.value} months`;
    case "gteMultiple":
      return `> ${((t.value - 1) * 100).toFixed(0)}% over`;
    case "gteEur":
      return `≥ €${t.value.toLocaleString("en-US")}`;
    case "cpvPrefix":
      return `CPV ${t.value}`;
  }
};

