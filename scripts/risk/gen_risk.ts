const OUTPUTS: { file: string; build: () => string }[] = [
  { file: HANDBOOK, build: buildHandbook },
  { file: JSON_OUT, build: buildJson },
];

const main = (): void => {
  const check = process.argv.includes("--check");
  const stale: string[] = [];

  for (const { file, build } of OUTPUTS) {
    const next = build();
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === next) continue;
    if (check) {
      stale.push(path.relative(ROOT, file));
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, next);
    console.log(`  wrote ${path.relative(ROOT, file)}`);
  }

  if (check && stale.length) {
    console.error(
      `✗ stale generated artifact(s): ${stale.join(", ")}\n` +
        "  Run `npm run gen:risk` and commit the result.",
    );
    process.exit(1);
  }
  console.log(check ? "✓ generated artifacts are current" : "done");
};

main();
