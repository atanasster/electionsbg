// Classify a КИД-2008 (NACE Rev.2) 2-digit division from a Bulgarian activity
// LABEL, for the procurement declared-activity mismatch flag
// (docs/plans/nkid-cpv-mismatch-v1.md, plan §8 B1).
//
// WHY NOT THE CODE: the CR Deeds НКИД field ("Клас по НКИД: …") carries codes from
// BOTH classification versions — НКИД-2003 (NACE Rev.1.1) and КИД-2008 (NACE Rev.2)
// — and the two REUSE the same division numbers for different sectors (45 =
// construction in Rev.1.1 but motor-trade in Rev.2; 51 = wholesale vs air transport;
// 74 = all business services vs other-professional). The numeric code is therefore
// ambiguous without knowing its version, and format (dotted vs 4-digit) does not
// discriminate. The Bulgarian LABEL text is the one reliable signal, so we classify
// the Rev.2 division from it and feed that to the Rev.2 crosswalk (naceCpv.ts).
//
// CONSERVATIVE BY DESIGN: this feeds a public "off-profile" accusation, so precision
// beats recall. A label with no confident keyword match returns null → the flag is
// UNAVAILABLE (no opinion), never a guess. Rules are ORDERED — the first match wins —
// so specific phrases MUST precede the generic ones they contain (e.g. "автомобилни
// горива" → retail-47 before the generic "автомобил" → motor-trade-45; "строителен
// надзор" → engineering-71 before the generic "строител" → construction-41).
//
// Validated exhaustively against the real crawled corpus by naceLabel.data.test.ts:
// every distinct label's resolved division is checked, and the unmatched share is
// held below a ceiling so a vocabulary drift surfaces rather than silently widening
// the "unavailable" set.

