/**
 * Classify a КИД-2008 (NACE Rev.2) 2-digit division from a Bulgarian activity
 * label. Returns null when no rule matches with confidence — the CONSERVATIVE
 * default that leaves the nkidMismatch flag unavailable rather than guessing.
 *
 * The input is the raw CR_F_6a_L field text ("Група по НКИД: 51.90 Клас по НКИД:
 * Друга търговия на едро") or just its description; the numeric code within it is
 * harmless to the keyword rules.
 */
export const naceDivisionFromLabel = (
  label: string | null | undefined,
): string | null => {
  if (!label) return null;
  const s = label.toLowerCase().replace(/\s+/g, " ").trim();
  if (!s) return null;
  for (const { re, div } of RULES) if (re.test(s)) return div;
  return null;
};
